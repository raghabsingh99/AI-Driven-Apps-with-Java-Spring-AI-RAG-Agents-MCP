package com.course.demo.advisor;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.ai.chat.client.ChatClientRequest;
import org.springframework.ai.chat.client.ChatClientResponse;
import org.springframework.ai.chat.client.advisor.api.AdvisorChain;
import org.springframework.ai.chat.client.advisor.api.BaseAdvisor;
import org.springframework.ai.chat.messages.AssistantMessage;
import org.springframework.ai.chat.model.ChatResponse;
import org.springframework.ai.chat.model.Generation;

import java.util.List;

public class DisclaimerAdvisor implements BaseAdvisor {

    private static final Logger log = LoggerFactory.getLogger(DisclaimerAdvisor.class);
    private static final String DISCLAIMER = "\n\nDisclaimer: This response was generated by AI and may be inaccurate.";

    @Override
    public ChatClientRequest before(ChatClientRequest chatClientRequest, AdvisorChain advisorChain) {
        return chatClientRequest;
    }

    @Override
    public ChatClientResponse after(ChatClientResponse chatClientResponse, AdvisorChain advisorChain) {
        log.info("[after] DisclaimerAdvisor: appending disclaimer");
        ChatResponse chatResponse = chatClientResponse.chatResponse();
        if (chatResponse == null) {
            return chatClientResponse;
        }

        List<Generation> generations = chatResponse.getResults().stream()
                .map(generation -> {
                    AssistantMessage output = generation.getOutput();
                    AssistantMessage disclaimedOutput = AssistantMessage.builder()
                            .content(output.getText() + DISCLAIMER)
                            .properties(output.getMetadata())
                            .toolCalls(output.getToolCalls())
                            .media(output.getMedia())
                            .build();
                    return new Generation(disclaimedOutput, generation.getMetadata());
                })
                .toList();

        ChatResponse mutatedChatResponse = ChatResponse.builder()
                .from(chatResponse)
                .generations(generations)
                .build();

        return chatClientResponse.mutate()
                .chatResponse(mutatedChatResponse)
                .build();
    }

    @Override
    public int getOrder() {
        return 100;
    }
}
